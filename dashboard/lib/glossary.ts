/** 용어를 찾는다. 없으면 null — 없는 설명을 지어내지 않는다. */
export function lookup(term: string): TermDef | null {
  return GLOSSARY[term] ?? null;
}

/** 툴팁 한 줄(title 속성용). 정의 + 부연을 이어 붙인다. */
export function tooltip(term: string): string | undefined {
  const def = GLOSSARY[term];
  if (!def) return undefined;
  return def.detail ? `${def.short}\n\n${def.detail}` : def.short;
}

