// ═══════════════════════════════════════════════════════════════════
// 전망값 — **데이터에서 계산한다.** 손으로 적지 않는다.
// ═══════════════════════════════════════════════════════════════════
export interface Projection {
  /** 다음 분기 매출 성장률 예상 범위(%). */
  revenue: [number, number] | null;
  /** 다음 분기 영업이익 성장률 예상 범위(%). */
  op: [number, number] | null;
  /** 어떻게 계산했는지. 숫자만 있으면 신뢰할 수 없다. */
  basis: string;
}

/**
 * 다음 분기 성장률 범위를 낸다.
 *
 * 방법: **현재 중앙값 + 전분기 대비 변화(모멘텀)를 절반만 이어 붙인다.**
 *   상단 = 중앙값 + delta/2   (모멘텀이 이어진다고 볼 때)
 *   하단 = 중앙값             (모멘텀이 소멸한다고 볼 때)
 *
 * ★ 모멘텀을 **온전히** 이어 붙이지 않는 이유: 성장률 변화는 평균회귀가 강하다.
 *   그대로 연장하면 두 분기 만에 비현실적인 숫자가 나온다.
 * ★ 이건 **예측 모델이 아니다.** "이 추세가 이어지면 이 범위"라는 조건부 서술이고,
 *   화면에 그 사실을 그대로 밝힌다.
 * ★ 델타가 없으면(지난 분기 비교 불가) 범위를 만들지 않는다 — null이다.
 */
export function projectSector(row: {
  revenueYoy: number | null;
  opYoy: number | null;
  revenueYoyDelta: number | null;
  opYoyDelta: number | null;
}): Projection {
  const band = (
    mid: number | null,
    delta: number | null
  ): [number, number] | null => {
    if (mid == null || delta == null) return null;
    const carried = mid + delta / 2;
    return carried >= mid ? [mid, carried] : [carried, mid];
  };
  return {
    revenue: band(row.revenueYoy, row.revenueYoyDelta),
    op: band(row.opYoy, row.opYoyDelta),
    basis:
      "이번 분기 중앙값을 하단, 전분기 대비 변화의 절반을 더한 값을 상단으로 잡았다. " +
      "성장률 변화는 평균회귀가 강해 모멘텀을 온전히 연장하지 않는다.",
  };
}
