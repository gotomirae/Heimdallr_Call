#:   업종 문구는 업종 칸에서만 판단 근거로 쓴다.
INDUSTRY_ONLY_KEYWORDS: frozenset[str] = frozenset({
    "방송 장비",
    "일반 목적용 기계",
    "특수 목적용 기계",
    "금속 가공",
    "전문, 과학",
    "전기업",
    "인터넷 정보매개",
    "정보 서비스",
})

#: 분류하지 못한 종목. **억지로 끼워 맞추지 않는다.**
UNKNOWN_SECTOR = "기타"

#: 화면 필터에 쓸 전체 목록(규칙 순서 + 기타).
ALL_SECTORS: tuple[str, ...] = tuple(name for name, _ in SECTOR_RULES) + (UNKNOWN_SECTOR,)


def _haystack(*parts: str | None) -> str:
    """비교용 문자열. 소문자 + 공백 정규화."""
    joined = " ".join(p for p in parts if p)
    return re.sub(r"\s+", " ", joined).lower()


def _first_hit(text: str, *, allow_industry_words: bool) -> str | None:
    """가장 **앞에서** 걸린 섹터. 같은 위치면 규칙 순서가 앞선 쪽.

    ★ 위치를 먼저 보는 이유: `products`는 본업을 앞에 적는다.
      규칙 순서만 보면 뒤에 곁다리로 붙은 한 단어가 본업을 덮어쓴다 —
      '승용차,중대형버스,트럭,민수특수차량,**군수차량**'이 방산이 되는 식이다.

    ★ 규칙 순서가 **동점 처리로 여전히 살아 있다**: '반도체 후공정장비'는
      '반도체'와 0번째에서 같이 걸리는데, 반도체장비가 규칙상 먼저라 이긴다.
    """
    if not text:
        return None
    best: tuple[int, int] | None = None
    best_sector: str | None = None
    for order, (sector, keywords) in enumerate(SECTOR_RULES):
        if any(bad in text for bad in SECTOR_EXCLUDES.get(sector, ())):
            continue  # 제외어에 걸리면 이 규칙은 없는 셈 친다
        usable = (
            keywords
            if allow_industry_words
            else tuple(k for k in keywords if k not in INDUSTRY_ONLY_KEYWORDS)
        )
        hits = [pos for pos in (text.find(k) for k in usable) if pos >= 0]
        if not hits:
            continue
        candidate = (min(hits), order)
        if best is None or candidate < best:
            best, best_sector = candidate, sector
    return best_sector


def classify_sector(
    name: str | None = None,
    industry: str | None = None,
    products: str | None = None,
) -> str:
    """투자 섹터명을 돌려준다. 못 가리면 `기타`.

    ★ **제품을 업종보다 먼저** 본다. 업종만 보면 '특수 목적용 기계 제조업' 93종목이
      전부 같은 섹터가 되는데, 그 안에 반도체장비·디스플레이장비·조선기자재가 섞여 있다.

    실측 대조 (2026-08-17, 실제 DB 값 그대로):
      한미반도체   / 특수 목적용 기계  / '반도체 후공정장비,반도체금형…'  → 반도체장비
      두산에너빌리티 / 일반 목적용 기계  / '기관,터어빈,선박용엔진,주단조품…' → 전력인프라
      셀트리온     / 기초 의약물질    / '램시마, 트룩시마, 허쥬마'        → 바이오·제약
      동성화인텍   / 기초 화학물질    / '초저온 보냉재'                 → 조선·해운

    ★ **분류는 DB에 적힌 것만 본다.** 두산에너빌리티의 products에는 '원자력'이
      한 글자도 없어서 원전으로 분류되지 않는다 — 투자자 인식과는 다를 수 있다.
      개별 종목을 손으로 박아 넣지 않는 이유: 1,322종목을 그렇게 관리할 수 없고,
      박아 넣은 값은 원자료가 바뀌어도 안 따라가 조용히 낡는다.
    """
    # 1차: 제품으로만 판정한다. 가장 구체적인 신호다.
    hit = _first_hit(_haystack(products), allow_industry_words=False)
    if hit is not None:
        return hit

    # 2차: 업종으로 떨어진다.
    #
    # ★ **회사명은 쓰지 않는다.** `name` 인자는 호출부 호환을 위해 남겨 두지만
    #   매칭에는 넣지 않는다 — 이름이 업종을 오염시켰다. '주성**엔지니어링**'이
    #   건설로, '한국**전력**공사'처럼 우연히 맞는 경우와 구분이 안 됐다.
    #   이름은 사업의 증거가 아니다.
    hit = _first_hit(_haystack(industry), allow_industry_words=True)
    if hit is not None:
        return hit

    return UNKNOWN_SECTOR


